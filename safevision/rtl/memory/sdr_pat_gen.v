// ============================================================================
// sdr_pat_gen.v — SDRAM 测试图案生成（可仿真 · 无引脚）
// ----------------------------------------------------------------------------
// 用途：给板级 bring-up 顶层 `top_sdram_loopback` 产生"要写进 SDRAM 的测试数据"。
//       读回时用**同一个**模块算期望值 —— 所以只要"写读两侧用同一份"，任何数据错误都会
//       被逐字比对抓住；而"能不能抓住**地址译码**错误"则取决于图案对地址有没有区分度。
//
// ★★ 为什么要单独抽成一个模块（而不是写成顶层里的一个 function）
//   `top_sdram_loopback` 例化的是安路**加密** SDRAM IP（`ip/sdram/sdr_*.enc.v`），
//   **进不了 ModelSim 回归**（见该文件头注）。但"图案对地址有没有区分度"是**纯组合逻辑**，
//   完全可以仿真 —— 抽出来就有一条 TB 守着，不必等烧板才发现问题。
//   这正是本项目对 `sdram_app_adapter` 用过的同一手法：**把不可仿真的一层尽量捞回仿真里**。
//
// ★★ 为什么图案必须依赖**全部 21 位地址**（本模块存在的第二个理由，2026-10-04）
//   `top_sdram_loopback` 的"全片稀疏扫描"用**步长 2049、1024 个点**铺满 2M word。
//   而旧写法（直接写在顶层里的 `pat_of`）只用了 `a[11:4]` 与 `a[7:0]`：在 `a = k<<11` 时
//   `a[7:0]` 全为 0、`a[11:4]` 只剩最低位有值 ⇒ **1024 个测试点只有 2 种图案**，
//   那个"全片扫描"几乎什么都证明不了。
//   ★ 这类错误**不会被"写读自比"发现**：写侧与读侧用同一个函数，错得一样照样 `BAD=0`
//     —— 所以必须由本模块的 TB 单独守住"区分度"这条性质。
//
// ----------------------------------------------------------------------------
// ★★★ 图案模式（`mode` 输入，2026-10-04 增加：不同模式针对不同的物理失效机理）
//   mode 0  ADDR   A d6f40a6 full-width signature: bytes encode addr[7:0],
//                  addr[12:5] and addr[20:13] with overlapping consistency bits.
//                  **单射**（可独立反解全部 21 位地址）⇒ 检测高位地址混叠。
//   mode 1  LFSR   xorshift32 伪随机（由地址**加非零常数**播种，保证永不为全 0）。
//                  **也是双射**（加法与 xorshift 每步都可逆）⇒ 不同地址仍得到不同图案，
//                  同时让 32 根数据线**高概率翻转** ⇒ 覆盖数据线之间的串扰 / 相邻线耦合。
//   mode 2  WALK1  walking-1：`1 << a[4:0]` —— **单根数据线为 1 在走**。
//                  最经典的"数据线粘连 / 短路 / 恒定故障"检测图案。
//                  ★ 注意它只依赖 a[4:0]，**不区分地址** —— 地址译码靠 mode 0。
//   mode 3  WALK0  walking-0：`~(1 << a[4:0])` —— 单根为 0 在走（补 WALK1 的另一半）。
//   mode 4  ALT    全 0 / 全 1 交替（按 a[0]）：最坏**功耗/电源噪声**图案。
//   mode 5  ADJ    相邻位交替：`a[0] ? 32'hAAAAAAAA : 32'h55555555` —— **相邻数据线反向翻转**，
//                  专压相邻线之间的耦合与保持时间。
//   ★ soak 时由顶层**逐轮轮换**这 6 种模式，让长时间运行覆盖多种失效机理。
//
// ★ 硬件规模：纯组合，21+3 位输入 → 32 位输出，约 80~120 个 LUT 量级，无寄存器、无状态。
//   只用位选 / 异或 / 移位，**不用 `/` `%`**（项目规则 §5 第 10 条）。
// ============================================================================

module sdr_pat_gen (
    input  wire [20:0] addr,    // word 地址（0 .. 2M-1）
    input  wire [2:0]  mode,    // 图案模式 0..5（见头注；>5 按 5 处理）
    output reg  [31:0] pat      // 该地址上的测试图案
);

    // ---- mode 0: full-width reversible signature (A d6f40a6) ----
    //   Byte 1 recovers addr[7:0]; byte 2 then recovers addr[12:5];
    //   byte 3 recovers addr[20:13]. Overlap bits [7:5]/[12:10] are checked by TB.
    wire [7:0] b0 = 8'hC3 ^ {addr[4:0], addr[7:5]};
    wire [7:0] b1 = 8'h3C ^ addr[7:0];
    wire [7:0] b2 = 8'h5A ^ addr[7:0] ^ addr[12:5];
    wire [7:0] b3 = 8'hA5 ^ addr[7:0] ^ addr[20:13];
    wire [31:0] p_addr = { b3, b2, b1, b0 };

    // ---- mode 1：xorshift32（双射，地址播种）----
    //   ★★ 种子用**加法**加一个非零常数，而不是异或：xorshift 的 0 是**不动点**，
    //      异或的话总有一个地址（addr = 常数低 21 位）会让种子变成 0、输出恒为 0 ——
    //      那就是"全 0 图案"，既是最弱的测试、又会掩盖"数据线卡死在 0"。
    //      加法保证 `{11'b0,addr} + C` 落在 [C, C+2^21) 内、**永不为 0**（C 远大于 2^21），
    //      而且加法是双射 ⇒ 整体仍是单射。
    //      （2026-10-04 由 `tb_sdr_pat_gen` 的 T6.2 抓出来的。）
    wire [31:0] x1 = { 11'b0, addr } + 32'hA5C3_5A3C;
    wire [31:0] x2 = x1 ^ (x1 << 13);
    wire [31:0] x3 = x2 ^ (x2 >> 17);
    wire [31:0] p_lfsr = x3 ^ (x3 << 5);

    // ---- mode 2/3：walking-1 / walking-0 ----
    wire [31:0] one = 32'd1 << addr[4:0];
    wire [31:0] p_w1 = one;
    wire [31:0] p_w0 = ~one;

    // ---- mode 4/5：全 0 全 1 交替 / 相邻位交替 ----
    wire [31:0] p_alt = addr[0] ? 32'hFFFFFFFF : 32'h00000000;
    wire [31:0] p_adj = addr[0] ? 32'hAAAAAAAA : 32'h55555555;

    always @(*) begin
        case (mode)
            3'd0:    pat = p_addr;
            3'd1:    pat = p_lfsr;
            3'd2:    pat = p_w1;
            3'd3:    pat = p_w0;
            3'd4:    pat = p_alt;
            default: pat = p_adj;
        endcase
    end

endmodule
