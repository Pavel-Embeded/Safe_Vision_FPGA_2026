"""Expand CDC constraints to the installed TD SDC dialect, plus Tcl audit.

TD read_sdc is deferred and is not a general Tcl interpreter. Do not wrap a
get_* expression in user procedures, variables or loops inside the SDC file.
"""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
FLOW=ROOT/'safevision/platform/anlogic_eg4s20_hx4s20c/project/v3_board_verify'
FIRST='*req_meta *ack_meta frame_heartbeat_sync/meta pll_loss_sync/meta locks_meta* video/media_m1 video/media_p1 video/safe_p1 video/fault_s1 video/fault_p1 video/cache/pixel_fault_meta video/cache/*store/done_meta video/cache/*store/fault_meta'
MAILBOXES='ref_status_mailbox mem_status_mailbox hdmi_status_mailbox video/config_mailbox video/audio_ready_mailbox video/status_mailbox video/cache/requests video/cache/responses audio/ring_to_ref audio/index_to_sys audio/index_to_mem audio/commit_to_mem audio/ready_to_sys audio/control_to_audio audio/status_to_sys'.split()
def main():
 s=['# Generated by tools/gen_v3_cdc.py. Standard expanded SDC only.',
 '# The separate v3_cdc_audit.tcl checks mapped object presence in normal Tcl.',
 '# MEM50 -> SYS100 packed packet payload/control retain real setup/hold.',
 'set_false_path -to [get_regs {'+FIRST+'}]',
 'set_false_path -through [get_nets {control_common_rst_n media_common_rst_n tx_reset}] -to [get_pins {*.sr */*.sr}]']
 groups=[('first_stage_synchronizers','get_regs',FIRST),('asynchronous_reset_roots','get_nets','control_common_rst_n media_common_rst_n tx_reset')]
 for mb in MAILBOXES:
  s.append('# '+mb+': payload held from request through returned ACK; 8ns bounds physical flight.')
  s.append('set_max_delay -datapath_only -from [get_regs {'+mb+'/payload*}] -to [get_regs {'+mb+'/dst_data*}] 8.000')
  groups += [(mb+'.payload','get_regs',mb+'/payload*'),(mb+'.capture','get_regs',mb+'/dst_data*')]
 for direction in ('wr_to_rd','rd_to_wr'):
  source='*'+direction+'*primary_addr_gray_reg*';target='*'+direction+'*sync_r1*'
  s.append('set_max_delay -datapath_only -from [get_regs {'+source+'}] -to [get_regs {'+target+'}] 8.000')
  groups += [(direction+'.gray','get_regs',source),(direction+'.meta','get_regs',target)]
 sink='sink/fa_sync[0] sink/td_sync[0] sink/sl_sync[0] sink/sl_sync[1]'
 player='player/mr_sync[0] player/fd_sync[0] player/lok_sync[0]'
 s+=['# Only metadata/completion first sampling stages; later local stages stay timed.',
  'set_false_path -to [get_regs {'+sink+'}]','set_false_path -to [get_regs {'+player+'}]']
 groups += [('sink_frame_first','get_regs',sink),('player_completion_first','get_regs',player),('spi_receive_input_boundary','get_pins','sd_miso_syn_*.ipad')]
 # Presence audits only: none of these groups generates a timing exception.
 for name in ('packet_data','packet_position','packet_stream','packet_last','request_toggle','high_data','high_position','high_pending','seen_toggle'):
  groups.append(('related_clock_packet.'+name,'get_regs','video/cache/*store/'+name+'*'))
 (FLOW/'v3_cdc.sdc').write_text('\n'.join(s)+'\n',encoding='utf-8')
 audit=['# Normal Tcl only. Not read_sdc. Object matches are not timing closure.',
  'set ::v3_audit_log [open constraint.objects.tsv w]',
  'puts $::v3_audit_log "label\\tmatched_objects"',
  'proc v3_expect_objects {label objects} {',
  ' if {[llength $objects]==0} {error "V3 empty mapped collection: $label"}',
  ' puts $::v3_audit_log "$label\\t[llength $objects]"','}']
 for label,cmd,pattern in groups:audit.append('v3_expect_objects {'+label+'} ['+cmd+' {'+pattern+'}]')
 audit+=['close $::v3_audit_log','unset ::v3_audit_log']
 (FLOW/'v3_cdc_audit.tcl').write_text('\n'.join(audit)+'\n',encoding='utf-8')
 print('Wrote expanded SDC and '+str(len(groups))+' mapped-object audits')
if __name__=='__main__':main()
