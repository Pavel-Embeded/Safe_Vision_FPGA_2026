"""Verify the curated functional checkpoint using its local source bytes.

Run against the exact validated_worktree delivery, not a Git archive whose
text filters may change CRLF bytes. This is not STA or hardware acceptance.
"""
import argparse,hashlib,json,re,sys,tempfile
from pathlib import Path
from audit_v3_raw_logs import audit_file

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def read(path):return json.loads(path.read_text(encoding='utf-8'))
def local(root,name):
 p=(root/name).resolve()
 if not p.is_relative_to(root.resolve()):raise ValueError('source/evidence path escaped root: '+name)
 return p
def sources(root,folder,negative=None):
 before=read(folder/'sources.sha256.json');assert before,'empty source fingerprint'
 after=folder/'sources.after.sha256.json'
 if after.exists():assert read(after)==before,'before/after source drift'
 mutated=[]
 for name,digest in before.items():
  assert re.fullmatch('[0-9a-f]{64}',digest),'invalid SHA256'
  path=local(folder,name.split(':',1)[1]) if name.startswith('generated:') else local(root,name)
  if negative and digest==negative['mutated_sha256']:
   assert sha(path)==negative['original_sha256'],'negative baseline changed: '+name
   mutants=[p for p in folder.glob('*.v') if sha(p)==digest];assert len(mutants)==1,'missing/ambiguous exact mutant'
   mutated.append(name)
  else:assert path.is_file() and sha(path)==digest,'source/generated bytes differ: '+name
 if negative:assert len(mutated)==1,'missing/ambiguous mutated source binding'
 return len(before)
def audit(root,selected):
 j=read(selected);assert j['complete'] and j['positive_native_tests']==100
 assert len(j['selected_runsets'])==28 and len(set(j['unique_tops']))==100
 seen=set();rows=[]
 for row in j['selected_runsets']:
  folder=local(root,row['evidence']);result=read(folder/'results.json')
  assert sha(folder/'results.json')==row['result_sha256'] and result['complete'],'changed/incomplete results'
  assert row['native_tests']==len(row['tops']) and not seen.intersection(row['tops']),'duplicate tests'
  seen.update(row['tops']);legacy=row['suite'].startswith('legacy_')
  if legacy:
   assert result['process_exit']==0 and result['source_unchanged'];source_count=sources(root,folder)
   logs=[folder/(top+'_sim.log') if row['suite']=='legacy_b' else folder/top/'sim.log' for top in row['tops']]
  else:
   actual=[v['top'] for v in result['results']];assert actual==row['tops']
   assert all(v['status']=='PASS' and not v.get('source_overrides') for v in result['results'])
   source_count=sum(sources(root,folder/top) for top in row['tops']);logs=[folder/top/'sim.log' for top in row['tops']]
  audits=[audit_file(log,not legacy) for log in logs];assert all(v['accepted'] for v in audits),('raw positive failure',row['key'],audits)
  rows.append({'key':row['key'],'native_tests':len(logs),'source_bindings_checked':source_count,'raw_logs_verified':True})
 assert seen==set(j['unique_tops']) and len(seen)==100
 negatives=[]
 for group in j['strict_negative_controls']:
  folder=local(root,group['evidence']);meta=read(folder/'negative_controls.json');assert meta['complete'] and meta['originals_preserved']
  cases=meta.get('cases',meta.get('negative_controls'));assert len(cases)==group['mutants']
  for case in cases:
   out=folder/case['mutation'];assert case['detected'] and case['normal_completion'];sources(root,out,case)
   text=(out/'sim.log').read_text(encoding='utf-8',errors='replace')
   assert '$finish called' in text and not re.search(r'(?im)^\s*(?:Fatal:|FATAL\b|ERROR:)',text)
   assert re.search(r'PASS\s+'+re.escape(case['top'])+r'\b|\[TB\]\s*'+re.escape(case['top'])+r'\s+done',text)
   values=[int(x) for x in re.findall(r'errors\s*=\s*(\d+)',text)]
   assert values==case['error_counts'] and any(values) and '[FAIL' in text
   if 'required_marker' in case:assert case['required_marker'] in text
   negatives.append(case['mutation'])
 assert len(negatives)==13 and len(set(negatives))==13
 return {'accepted':True,'positive_native_tests':100,'strict_negative_controls':13,'runsets':rows,'production_source_bytes_verified':True,'release_ready':False,'hardware_verified':False,'routed_sta_verified':False}
def selftest(directory):
 with tempfile.TemporaryDirectory(prefix='v3_checkpoint_audit_',dir=directory.resolve()) as temp:
  root=Path(temp);folder=root/'evidence';folder.mkdir();(root/'sample.v').write_bytes(b'module sample; endmodule\n')
  f=folder/'sources.sha256.json';f.write_text(json.dumps({'sample.v':sha(root/'sample.v')}),encoding='utf-8');assert sources(root,folder)==1
  (root/'sample.v').write_bytes(b'module changed; endmodule\n')
  try:sources(root,folder)
  except AssertionError:pass
  else:raise AssertionError('stale source was accepted')
  try:local(root,'../escaped.v')
  except ValueError:pass
  else:raise AssertionError('escaped source was accepted')
 return {'accepted':True,'checks':3,'scope':'audit helper selftest, not native RTL simulation'}
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--repo',type=Path,default=Path(__file__).resolve().parents[2]);ap.add_argument('--selected',type=Path);ap.add_argument('--output',type=Path,required=True);ap.add_argument('--self-test',action='store_true');a=ap.parse_args()
 a.output.parent.mkdir(parents=True,exist_ok=True)
 try:result=selftest(a.output.parent) if a.self_test else audit(a.repo.resolve(),a.selected or a.repo/'evidence/v3/current_100_20261016/selected_acceptance.json')
 except Exception as ex:result={'accepted':False,'error':str(ex),'release_ready':False}
 a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8');print(json.dumps(result));return 0 if result['accepted'] else 1
if __name__=='__main__':sys.exit(main())
